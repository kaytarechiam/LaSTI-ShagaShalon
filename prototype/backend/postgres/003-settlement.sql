-- Additive migration for existing databases. Apply once before deploying this version.
BEGIN;
CREATE TABLE IF NOT EXISTS invoices (
  reservation text PRIMARY KEY REFERENCES visits(reservation),
  original_total integer NOT NULL CHECK (original_total >= 0),
  total integer NOT NULL CHECK (total >= 0), created bigint NOT NULL,
  created_by integer NOT NULL REFERENCES accounts(id)
);
CREATE TABLE IF NOT EXISTS invoice_adjustments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation text NOT NULL REFERENCES invoices(reservation), old_total integer NOT NULL,
  new_total integer NOT NULL CHECK (new_total >= 0), reason text NOT NULL,
  actor integer NOT NULL REFERENCES accounts(id), created bigint NOT NULL
);
CREATE TABLE IF NOT EXISTS payments (
  reservation text PRIMARY KEY REFERENCES invoices(reservation),
  amount integer NOT NULL CHECK (amount >= 0), method text NOT NULL CHECK (method IN ('CASH','TRANSFER','OTHER')),
  actor integer NOT NULL REFERENCES accounts(id), created bigint NOT NULL
);
CREATE TABLE IF NOT EXISTS feedback (
  reservation text PRIMARY KEY REFERENCES visits(reservation),
  account integer NOT NULL REFERENCES accounts(id), rating integer NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment text NOT NULL DEFAULT '', created bigint NOT NULL
);
CREATE TABLE IF NOT EXISTS feedback_followups (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation text NOT NULL REFERENCES feedback(reservation),
  note text NOT NULL, actor integer NOT NULL REFERENCES accounts(id), created bigint NOT NULL
);
COMMIT;
