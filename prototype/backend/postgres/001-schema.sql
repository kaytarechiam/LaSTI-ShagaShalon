-- Initial PostgreSQL schema. Apply only to a new empty database.
-- This does not import local SQLite data.
BEGIN;

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE accounts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text UNIQUE NOT NULL, name text NOT NULL, phone text NOT NULL,
  password text NOT NULL, role text NOT NULL
);
CREATE TABLE sessions (
  token text PRIMARY KEY, account integer NOT NULL REFERENCES accounts(id), expires bigint NOT NULL
);
CREATE TABLE auth_attempts (key text PRIMARY KEY, count integer NOT NULL, expires bigint NOT NULL);
CREATE INDEX auth_attempts_expires ON auth_attempts(expires);
CREATE TABLE reservations (
  id text PRIMARY KEY, account integer NOT NULL REFERENCES accounts(id),
  service text NOT NULL, capster text NOT NULL, day text NOT NULL,
  start bigint NOT NULL, "end" bigint NOT NULL, name text NOT NULL, phone text NOT NULL,
  status text NOT NULL DEFAULT 'REQUESTED', code text UNIQUE,
  created_order bigint GENERATED ALWAYS AS IDENTITY UNIQUE
);
CREATE TABLE allocations (
  reservation text PRIMARY KEY REFERENCES reservations(id), capster text NOT NULL,
  start bigint NOT NULL, "end" bigint NOT NULL, CHECK (start < "end"),
  EXCLUDE USING gist (capster WITH =, int8range(start, "end", '[)') WITH &&)
);
CREATE INDEX allocations_interval ON allocations(capster, start, "end");
CREATE TABLE simulated_notifications (
  reservation text PRIMARY KEY REFERENCES reservations(id), created bigint NOT NULL
);
CREATE TABLE salon_config (
  id integer PRIMARY KEY, version integer NOT NULL, data text NOT NULL, updated bigint, actor integer
);
CREATE TABLE salon_drafts (
  account integer PRIMARY KEY REFERENCES accounts(id), version integer NOT NULL, data text NOT NULL
);
CREATE TABLE capster_accounts (
  account integer PRIMARY KEY REFERENCES accounts(id), capster text UNIQUE NOT NULL
);
CREATE TABLE capster_ready (capster text PRIMARY KEY, ready integer NOT NULL);
CREATE TABLE visits (
  reservation text PRIMARY KEY REFERENCES reservations(id), day text NOT NULL, ticket integer NOT NULL,
  status text NOT NULL, arrived bigint NOT NULL, started bigint, ended bigint, estimate bigint,
  channel text NOT NULL, request_key text UNIQUE, UNIQUE(day, ticket)
);
CREATE TABLE booking_terms (
  reservation text PRIMARY KEY REFERENCES reservations(id), price integer NOT NULL, duration integer NOT NULL
);
CREATE TABLE reservation_items (
  reservation text NOT NULL REFERENCES reservations(id), position integer NOT NULL,
  service text NOT NULL, name text NOT NULL, price integer NOT NULL, duration integer NOT NULL,
  PRIMARY KEY(reservation, position), UNIQUE(reservation, service)
);
CREATE TABLE salon_events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor integer NOT NULL, subject text NOT NULL, action text NOT NULL, at bigint NOT NULL
);

COMMIT;
